"""Original code/data RVAs used only by the regional CPU replay suite."""
from pathlib import Path
REGION = "Europe"

def select(path):
    global REGION
    REGION = Path(path).name
    if REGION not in ("Europe", "USA", "Germany", "Italy-Covermount"):
        raise ValueError("Specify an individual region fixture directory")

def italian():
    return REGION == "Italy-Covermount"

def rva(english):
    if REGION in ("Europe", "USA"):
        return english
    return RVAS[english][1 if italian() else 0]

def crt_address(rig, english):
    german, italian_slot = CRT[english]
    if italian():
        return int.from_bytes(rig.u.mem_read(rig.shellbase+italian_slot,4), "little")
    return rig.shellbase+(german if REGION == "Germany" else english)

